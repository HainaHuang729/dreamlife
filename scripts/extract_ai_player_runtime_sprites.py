#!/usr/bin/env python3
"""LEGACY: extract old AI-generated player atlases into 32x40 PNG sprites.

Do not use this for the current runtime art pipeline. Current character assets
are locked to 96x120 with foot anchor (48, 108); use
scripts/build_player_motion_96.py and scripts/build_player_tool_actions_96.py.

Input atlases were generated by imagegen on a green chroma-key background.
Output sprites match the historical 32x40 contract:
stardew-tilemap-from-zero/assets/game/player/<action>_<direction>.png
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
RUN_DIR = ROOT / "asset_runs" / "run_015_ai_player_runtime_sprites"
SOURCE_DIR = RUN_DIR / "source"
PROCESSED_DIR = RUN_DIR / "processed"
PLAYER_DIR = ROOT / "stardew-tilemap-from-zero" / "assets" / "game" / "player"
TARGET_SIZE = (32, 40)
DIRECTIONS = ["down", "up", "left", "right"]


@dataclass(frozen=True)
class AtlasSpec:
    filename: str
    rows: list[str]
    cols: list[str]


ATLASES = [
    AtlasSpec(
        "movement_inspect_atlas.png",
        ["idle", "walk", "run", "inspect"],
        DIRECTIONS,
    ),
    AtlasSpec(
        "tools_harvest_atlas.png",
        ["hoe", "seeds", "wateringCan", "scythe", "harvest"],
        DIRECTIONS,
    ),
    AtlasSpec(
        "fishing_atlas.png",
        ["fishingRod", "fishingCatch"],
        DIRECTIONS,
    ),
    AtlasSpec(
        "sleep_warp_atlas.png",
        ["sleep", "warp"],
        DIRECTIONS,
    ),
]


def is_chroma_green(r: int, g: int, b: int) -> bool:
    return g >= 120 and r <= 95 and b <= 95 and g >= r * 1.55 and g >= b * 1.55


def remove_green(image: Image.Image) -> Image.Image:
    rgba = image.convert("RGBA")
    pixels = rgba.load()
    width, height = rgba.size
    for y in range(height):
        for x in range(width):
            r, g, b, a = pixels[x, y]
            if is_chroma_green(r, g, b):
                pixels[x, y] = (0, 0, 0, 0)
    return rgba


def alpha_bbox(image: Image.Image) -> tuple[int, int, int, int] | None:
    alpha = image.getchannel("A")
    return alpha.getbbox()


def pad_box(box: tuple[int, int, int, int], pad: int, size: tuple[int, int]) -> tuple[int, int, int, int]:
    left, top, right, bottom = box
    width, height = size
    return (
        max(0, left - pad),
        max(0, top - pad),
        min(width, right + pad),
        min(height, bottom + pad),
    )


def pixelate_resize(image: Image.Image, size: tuple[int, int]) -> Image.Image:
    return image.resize(size, Image.Resampling.NEAREST)


def normalize_cell(cell: Image.Image, action: str) -> Image.Image:
    clean = remove_green(cell)
    box = alpha_bbox(clean)
    out = Image.new("RGBA", TARGET_SIZE, (0, 0, 0, 0))
    if not box:
        return out

    box = pad_box(box, 8, clean.size)
    subject = clean.crop(box)
    src_w, src_h = subject.size

    # Leave a little bottom room so the runtime anchor still lands near the feet.
    max_w = 31
    max_h = 37
    if action in {"fishingRod", "fishingCatch", "scythe", "hoe"}:
        max_w = 32
        max_h = 38
    scale = min(max_w / src_w, max_h / src_h)
    dest_w = max(1, int(round(src_w * scale)))
    dest_h = max(1, int(round(src_h * scale)))
    subject = pixelate_resize(subject, (dest_w, dest_h))

    paste_x = (TARGET_SIZE[0] - dest_w) // 2
    paste_y = 37 - dest_h
    if paste_y < 0:
        paste_y = 0
    if action == "sleep":
        paste_y = min(3, paste_y + 2)

    out.alpha_composite(subject, (paste_x, paste_y))
    return out


def crop_grid_cell(image: Image.Image, row: int, col: int, rows: int, cols: int) -> Image.Image:
    width, height = image.size
    left = round(col * width / cols)
    right = round((col + 1) * width / cols)
    top = round(row * height / rows)
    bottom = round((row + 1) * height / rows)
    return image.crop((left, top, right, bottom))


def make_contact_sheet(frames: dict[tuple[str, str], Image.Image]) -> Image.Image:
    actions = [action for spec in ATLASES for action in spec.rows]
    cell_w, cell_h = 34, 42
    sheet = Image.new("RGBA", (cell_w * len(DIRECTIONS), cell_h * len(actions)), (0, 0, 0, 0))
    for row, action in enumerate(actions):
        for col, direction in enumerate(DIRECTIONS):
            frame = frames[(action, direction)]
            sheet.alpha_composite(frame, (col * cell_w + 1, row * cell_h + 1))
    return sheet


def main() -> None:
    PLAYER_DIR.mkdir(parents=True, exist_ok=True)
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    frames: dict[tuple[str, str], Image.Image] = {}

    for spec in ATLASES:
        atlas_path = SOURCE_DIR / spec.filename
        atlas = Image.open(atlas_path).convert("RGB")
        for row, action in enumerate(spec.rows):
            for col, direction in enumerate(spec.cols):
                cell = crop_grid_cell(atlas, row, col, len(spec.rows), len(spec.cols))
                frame = normalize_cell(cell, action)
                frames[(action, direction)] = frame
                name = f"{action}_{direction}.png"
                frame.save(PLAYER_DIR / name)
                frame.save(PROCESSED_DIR / name)

    contact = make_contact_sheet(frames)
    contact.save(RUN_DIR / "ai_player_runtime_contact.png")
    print(f"extracted {len(frames)} AI-generated runtime sprites")
    print(f"runtime dir: {PLAYER_DIR}")
    print(f"contact sheet: {RUN_DIR / 'ai_player_runtime_contact.png'}")


if __name__ == "__main__":
    main()
